"""One negotiation with real LLM agents (LLM_MODE=online), happy path only.

  python scripts/run_online_negotiation.py                     # LLM_PROVIDER from .env (default anthropic)
  python scripts/run_online_negotiation.py --provider groq     # OpenAI-compatible Groq API

Needs ANTHROPIC_API_KEY (anthropic) or GROQ_API_KEY (groq) in .env. Starts the four services with LLM_MODE=online and the ledger disabled (this run is
about the agents; the ledger evidence is the offline run in docs/EXECUTION_EVIDENCE.md), verifies the invoice and
runs the negotiation. Writes evidence/negotiation_transcript_online.json and the "Online LLM run" section of
docs/EXECUTION_EVIDENCE.md. Every round records whether the model answered (mode=online, fallback=false) or the
deterministic fallback had to step in; the section reports those counts as they are.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from services.common.config import get_settings  # noqa: E402
from services.coordinator.run_flow import SERVICES, start_stack, stop_stack  # noqa: E402
from services.ledger import local_chain  # noqa: E402
from services.supplier import data as supplier_data  # noqa: E402

OUT = ROOT / "evidence" / "negotiation_transcript_online.json"
DOC = ROOT / "docs" / "EXECUTION_EVIDENCE.md"
BEGIN, END = "<!-- online-llm-run:begin -->", "<!-- online-llm-run:end -->"


def _ok(r: httpx.Response) -> dict:
    if r.status_code >= 400:
        raise SystemExit(f"{r.request.method} {r.request.url} -> {r.status_code}: {r.text}")
    return r.json()


def section(data: dict) -> str:
    n = data["negotiation"]
    rounds = n.get("rounds") or []
    online = sum(1 for r in rounds if r.get("mode") == "online" and not r.get("fallback"))
    fallback = sum(1 for r in rounds if r.get("fallback"))
    blocked = sum(len(r.get("blocked") or []) for r in rounds)
    lines = [
        "| Round | Side | Action | x | d | Mode | Fallback | Blocked by code | Rationale (model text) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rounds:
        why = (r.get("rationale") or "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {r['round']} | {r['side']} | {r['action']} | {r['x']:,.0f} | {r['d']:.1%} | {r.get('mode')} | "
                     f"{r.get('fallback')} | {len(r.get('blocked') or [])} | {why} |")
    cc = n.get("close_check") or {}
    close = (f"supplier feasible {cc.get('supplier_feasible')}, buyer feasible {cc.get('buyer_feasible')}, Nash product "
             f"{cc.get('nash_product', 0):,.0f} vs BILNO optimum {cc.get('optimum_nash_product', 0):,.0f}, within the "
             f"10% tolerance: {cc.get('within_tolerance')}") if cc else "not reached"
    stuck = [r for r in rounds if r.get("fallback")
             and not any(c["tool"] == "submit_offer" and c["status"] != "ok" for c in r.get("tool_calls") or [])
             and sum(c["tool"] == "evaluate_counter" for c in r.get("tool_calls") or []) >= 4]
    fb_note = (f" (in {len(stuck)} of them the model only kept calling `evaluate_counter`)" if stuck else "")
    agreed = n.get("agreed")
    result = (f"agreed x = {agreed['x']:,.0f} at d = {agreed['d']:.1%}" if agreed else "no agreement") + \
        f"; outcome `{n.get('outcome')}`; final state `{data['state']}`"
    return f"""{BEGIN}
## Online LLM run (real LLM agents)

Generated by `scripts/run_online_negotiation.py` on {data['started']} UTC with `LLM_MODE=online`.
Provider: **{data['provider']}** (`{data['base_url']}`), model **`{data['model']}`**. Both the Seller Agent and the
Buyer Agent used this model. Happy path only: invoice verification and negotiation. The ledger was disabled for this run
(`LEDGER_TARGET=none`), and no bank payment was made. Transcript: `evidence/negotiation_transcript_online.json`.

- Result: {result}. BILNO reference point: x = {n['bilno']['x']:,.0f}, d = {n['bilno']['d']:.1%}.
- Rounds answered by the model: **{online} of {len(rounds)}**; rounds where the deterministic fallback stepped in:
  **{fallback}**; offers blocked by the private-limit code: **{blocked}**.
- Close check (code, plan section 5.4): {close}.
- A fallback round means the model did not submit a valid move within 4 tool steps, so the agent's deterministic
  strategy made the move{fb_note}.
- The model only proposes. Every offer went through the same `validate_offer()` code as in the offline run.

{chr(10).join(lines)}
{END}"""


def write_section(data: dict) -> None:
    doc = DOC.read_text()
    block = section(data)
    if BEGIN in doc:
        doc = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    else:
        doc = doc.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(doc)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--provider", choices=["anthropic", "groq"])
    args = ap.parse_args()
    if args.provider:
        os.environ["LLM_PROVIDER"] = args.provider
    settings = get_settings()
    if settings.llm_provider == "groq":
        key, model, base_url = settings.groq_api_key, settings.groq_model, settings.groq_base_url
    else:
        key, model, base_url = settings.anthropic_api_key, settings.llm_model, "https://api.anthropic.com"
    if not key:
        raise SystemExit(f"no API key for provider {settings.llm_provider}: an online run is not possible (nothing written)")
    os.environ["LLM_MODE"] = "online"
    started = datetime.now(timezone.utc)
    run_dir = ROOT / "data" / "runs" / f"online-{started:%Y%m%d-%H%M%S}"
    os.environ["INVOICE_SERIES"] = f"L{started:%m%d%H%M%S}"
    ports = {n: local_chain.free_port() for n in SERVICES}
    procs, url, _ = start_stack("none", run_dir, ports, offline=False)
    try:
        coord = httpx.Client(base_url=url["coordinator"], timeout=900)
        invoice = supplier_data.invoice_number("0142")
        deal = _ok(coord.post("/invoices/intake", json={"invoice_number": invoice}))
        d = _ok(coord.post(f"/deals/{deal['deal_id']}/negotiate"))
    finally:
        stop_stack(procs)
    data = {"started": f"{started:%Y-%m-%d %H:%M}", "llm_mode": "online", "provider": settings.llm_provider,
            "base_url": base_url, "model": model,
            "ledger": "disabled (LEDGER_TARGET=none)", "invoice": invoice, "deal_id": deal["deal_id"],
            "state": d["state"], "negotiation": d["negotiation"]}
    OUT.write_text(json.dumps(data, indent=2) + "\n")
    write_section(data)
    print(section(data))
    print(f"\nWrote {OUT.relative_to(ROOT)} and the Online LLM run section of {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
